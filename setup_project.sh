#!/bin/bash

# ============================================================
# setup_project.sh — Create a new empirical research project
# ============================================================
#
# Usage:
#   bash setup_project.sh <project-name> [destination-path]
#
# Examples:
#   bash setup_project.sh My-New-Paper
#   bash setup_project.sh My-New-Paper ~/Dropbox/Research
#
# If no destination path is given, the project is created in
# the current working directory.
# ============================================================


set -e

# ---- Parse arguments ----------------------------------------

PROJECT_NAME="$1"
DEST_DIR="${2:-.}"

if [ -z "$PROJECT_NAME" ]; then
    echo ""
    echo "Usage: bash setup_project.sh <project-name> [destination-path]"
    echo ""
    echo "Examples:"
    echo "  bash setup_project.sh My-New-Paper"
    echo "  bash setup_project.sh My-New-Paper ~/Dropbox/Research"
    echo ""
    exit 1
fi

PROJECT_PATH="$DEST_DIR/$PROJECT_NAME"

# ---- Check for conflicts ------------------------------------

if [ -d "$PROJECT_PATH" ]; then
    echo "Error: Directory '$PROJECT_PATH' already exists."
    echo "Choose a different name or remove the existing directory."
    exit 1
fi

# ---- Locate the template directory --------------------------
# The script looks for the templates/ folder next to itself.
# This is where CLAUDE.md, rules, skills, and other templates live.

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
TEMPLATE_DIR="$SCRIPT_DIR/templates"

if [ ! -d "$TEMPLATE_DIR" ]; then
    echo "Warning: No templates/ directory found at $TEMPLATE_DIR"
    echo "The project structure will be created, but template files"
    echo "will need to be added manually."
    echo ""
    HAS_TEMPLATES=false
else
    HAS_TEMPLATES=true
fi

# ---- Create directory structure ------------------------------

echo "Creating project: $PROJECT_PATH"
echo ""

mkdir -p "$PROJECT_PATH"

# Code directories
mkdir -p "$PROJECT_PATH/Code/_Archive"
mkdir -p "$PROJECT_PATH/Code/_Claude Logs"
mkdir -p "$PROJECT_PATH/Code/_Claude Scripts/_Archive"

# Data directories
mkdir -p "$PROJECT_PATH/Data/Raw"
mkdir -p "$PROJECT_PATH/Data/Processed/_Archive"

# Output directories
mkdir -p "$PROJECT_PATH/Output/Tables/_Archive"
mkdir -p "$PROJECT_PATH/Output/Figures/_Archive"
mkdir -p "$PROJECT_PATH/Output/Processed Data"

# Supporting directories
mkdir -p "$PROJECT_PATH/Literature"
mkdir -p "$PROJECT_PATH/Paper"
mkdir -p "$PROJECT_PATH/Admin"

# Claude Code configuration directories
mkdir -p "$PROJECT_PATH/.claude/rules"

# ---- Copy template files -------------------------------------

if [ "$HAS_TEMPLATES" = true ]; then

    # Core files
    if [ -f "$TEMPLATE_DIR/CLAUDE.md" ]; then
        cp "$TEMPLATE_DIR/CLAUDE.md" "$PROJECT_PATH/CLAUDE.md"
        echo "  Copied CLAUDE.md (fill in the XXXX and AUTHOR_NAME placeholders)"
    fi

    if [ -f "$TEMPLATE_DIR/gitignore_template" ]; then
        cp "$TEMPLATE_DIR/gitignore_template" "$PROJECT_PATH/.gitignore"
        echo "  Copied .gitignore"
    fi

    if [ -f "$TEMPLATE_DIR/MEMORY.md" ]; then
        cp "$TEMPLATE_DIR/MEMORY.md" "$PROJECT_PATH/MEMORY.md"
        echo "  Copied MEMORY.md (memory index for cross-session context)"
    fi

    if [ -f "$TEMPLATE_DIR/PINBOARD.md" ]; then
        cp "$TEMPLATE_DIR/PINBOARD.md" "$PROJECT_PATH/PINBOARD.md"
        echo "  Copied PINBOARD.md (task tracking board)"
    fi

    if [ -f "$TEMPLATE_DIR/GLOSSARY.md" ]; then
        cp "$TEMPLATE_DIR/GLOSSARY.md" "$PROJECT_PATH/GLOSSARY.md"
        echo "  Copied GLOSSARY.md (per-project glossary; loaded at session start)"
    fi

    # Path-scoped rules
    if [ -d "$TEMPLATE_DIR/rules" ]; then
        cp "$TEMPLATE_DIR/rules/"* "$PROJECT_PATH/.claude/rules/"
        echo "  Copied path-scoped rules (.claude/rules/)"
    fi

    # Build registry script
    if [ -f "$TEMPLATE_DIR/build_registry.R" ]; then
        cp "$TEMPLATE_DIR/build_registry.R" "$PROJECT_PATH/Code/_Claude Scripts/build_registry.R"
        echo "  Copied build_registry.R (Code/_Claude Scripts/)"
    fi

    # Registry header
    if [ -f "$TEMPLATE_DIR/REGISTRY_header.md" ]; then
        cp "$TEMPLATE_DIR/REGISTRY_header.md" "$PROJECT_PATH/Code/REGISTRY.md"
        echo "  Created Code/REGISTRY.md (empty, auto-generated by build_registry.R)"
    fi

    # Settings
    if [ -f "$TEMPLATE_DIR/settings_local.json" ]; then
        cp "$TEMPLATE_DIR/settings_local.json" "$PROJECT_PATH/.claude/settings.local.json"
        echo "  Copied baseline permissions (.claude/settings.local.json)"
    fi

fi

# ---- Create starter README.md --------------------------------

cat > "$PROJECT_PATH/README.md" << 'READMEEOF'
# Project: XXXX

## Research Question

XXXX

## Authors

- XXXX

## Status

- [ ] Data cleaning
- [ ] Summary statistics
- [ ] Main estimation
- [ ] Robustness checks
- [ ] Paper draft
- [ ] Submission

