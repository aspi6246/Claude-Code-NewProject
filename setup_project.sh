│   ├── rules/                 # Path-scoped rules (auto-loaded by context)
│   │   ├── r-data-analysis.md # R coding conventions (Code/**, Data/**)
│   │   ├── paper-editing.md   # LaTeX conventions (Paper/**)
│   │   └── output-conventions.md # Output formats (Output/**)
│   └── settings.local.json    # Baseline permissions
├── Code/
│   ├── REGISTRY.md            # Auto-generated script dependency map
│   ├── _Archive/              # Superseded scripts
│   ├── _Claude Logs/          # Session progress logs
│   └── _Claude Scripts/       # Purled .R copies + build_registry.R
